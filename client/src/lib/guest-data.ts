export function isGuestSession(): boolean {
  if (typeof document === "undefined") return false;
  const cookies = document.cookie;
  return cookies.includes("is_guest=true") || cookies.includes("token=guest_");
}

export function getGuestRole(): "FOOD_COURT_ADMIN" | "RESTAURANT_VENDOR" | null {
  if (typeof document === "undefined") return null;
  const match = document.cookie.match(/(?:^|;\s*)user_role=([^;]*)/);
  const role = match ? decodeURIComponent(match[1]) : null;
  if (role === "FOOD_COURT_ADMIN" || role === "RESTAURANT_VENDOR") {
    return role;
  }
  return null;
}

